def main() -> None:
    data = json.loads(CARDS.read_text(encoding="utf-8"))
    cards = data["cards"]
    have = {c["id"] for c in cards}

    added = [c for c in NEW if c["id"] not in have]
    skipped = [c["id"] for c in NEW if c["id"] in have]
    if skipped:
        print(f"已存在，跳过：{skipped}")

    errs = []
    for c in added:
        need = ["id", "type", "domain", "stage", "context", "quote",
                "question", "options", "best", "explain", "principle", "action"]
        for k in need:
            if not c.get(k):
                errs.append(f"{c['id']} 缺字段 {k}")
        ids = [o["id"] for o in c["options"]]
        if len(ids) != len(set(ids)):
            errs.append(f"{c['id']} 选项 id 重复")
        if c["best"] not in ids:
            errs.append(f"{c['id']} best={c['best']} 不在选项里")
        if len(ids) != 4:
            errs.append(f"{c['id']} 选项不是 4 个")
    if errs:
        for e in errs:
            print("  " + e)
        sys.exit("校验失败，未写回")

    cards.extend(added)
    data["version"] = int(data.get("version", 1)) + 1
    # note 里补一句这个批次的立场，免得以后改内容的人把让/守的平衡改坏
    data["note"] = (data.get("note", "") +
                    " 另含一组「让 vs 守」日常卡（朋友/家人/公司职位/伴侣）："
                    "同一让步行为在低频时是关系维护（Rusbult 等 1991），"
                    "重复到第 N 次会形成共同反刍、同时抬高亲密度和抑郁焦虑（Rose 2002）。"
                    "这批卡的让/守答案刻意各占一半——只守会教出斤斤计较，只让会教出老好人。").strip()
    CARDS.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    from collections import Counter
    print(f"已加入 {len(added)} 张，共 {len(cards)} 张（version {data['version']}）")
    print("domain:", dict(Counter(c["domain"] for c in cards)))
    print("新卡:", [c["id"] for c in added])
    print("\n下一步：py -3 tools/gen_diagnosis.py " + " ".join(c["id"] for c in added))
    print("        py -3 tools/fix_plan_scripts.py")


if __name__ == "__main__":
    main()
