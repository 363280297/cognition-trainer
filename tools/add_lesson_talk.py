# -*- coding: utf-8 -*-
"""加一课：接话的结构。配合 4 张 t 卡（输出侧）。"""
import io
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CUR = os.path.join(ROOT, 'data', 'curriculum.json')

LESSON = {
    "id": "p30",
    "series": "日常沟通",
    "title": "接话：你这句话发出去，别人能接什么",
    "level": "A",
    "read": "群里冷场，多数时候不是别人不想聊，而是那句话本身没有可接的地方。"
            "有个很省事的检验：把你要发的话当成一个球，问一句「别人能接住什么」。"
            "能接的只有两类。一类是问一个具体的东西——在哪、什么时候、怎么样了、多少钱买的之外的那些；"
            "另一类是给出自己的相关具体信息（我也在、我上周也去过）。"
            "接不住的主要也有两类：对人和局面的评价（「又有新人加入了」「大家都挺努力」），"
            "以及已经收尾的总结（「厉害了」「不错」「加油」）。"
            "这两类听起来更像在参与，但它们把说话人的位置从场内挪到了场外，并且没有留入口。"
            "还有一种更隐蔽、代价也更大的：替在场的人排名次或分配身份。"
            "这类话没有「顺着说」的选项，只能接受或者反驳——接受等于承认自己低，"
            "反驳等于不给你面子，所以最省事的回应是沉默，或者一个尴尬的表情。",
    "warn": "这不是「每句话都必须能接」。熟人之间一句「厉害了」加个表情就够了，"
            "群里的沉默也常常只是大家在忙别的。这条规则只在你**自己觉得冷场、想弄清为什么**的时候有用。"
            "把它升级成人人必须遵守的说话规范，就会变成另一种表演——那种为了不让话题落地而"
            "不停抛问题的聊天，比沉默更累人。",
    "apply": {
        "q": "群里有人发了一张自己刚做的菜的照片，说「第一次做，居然没糊」。下面哪一句最接得下去？",
        "options": [
            "厉害了",
            "第一次做这个最容易糊锅，火候特别不好掌握",
            "看着不错，你这个是煎的还是烤的？",
            "我上次做菜也糊了，比你还惨",
        ],
        "answer": 2,
        "why": "「是煎的还是烤的」问的是一件具体的事：他答得出来，别人也能顺着说自己的做法——"
               "这是唯一一个把话头留在原地的选项。"
               "选项 2 是评价「做饭这件事」的一般规律，把话题从他这一次挪到了普遍层面，谁也接不上，"
               "这正是最常见的那个错。选项 1「厉害了」是句号，收到就结束了。"
               "选项 4 虽然还在同一个话题里，但你讲的是自己的故事，话筒被拿走了——"
               "它在熟人之间不算错，只是这里要比的是「谁最接得下去」。",
    },
}


def main():
    with io.open(CUR, encoding='utf-8') as f:
        data = json.load(f)
    lessons = data['lessons']
    if any(l['id'] == LESSON['id'] for l in lessons):
        print('已经加过了，跳过')
        return
    lessons.append(LESSON)
    with io.open(CUR, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('curriculum.json：%d 课（新增 %s）' % (len(lessons), LESSON['id']))


if __name__ == '__main__':
    main()
