def main():
    data = json.load(io.open(CUR, encoding='utf-8'))
    lessons = data['lessons']

    # 一、摘掉用户退掉的那一课
    dropped = [l for l in lessons if l['id'] == DROP]
    lessons = [l for l in lessons if l['id'] != DROP]
    if dropped:
        print('已摘掉 %s「%s」（用户说他要的不是这个）' % (DROP, dropped[0]['title']))

    # 二、追加三课
    have = set(l['id'] for l in lessons)
    ids = [l['id'] for l in LESSONS]
    if len(set(ids)) != len(ids):
        sys.exit('本文件里的 id 自己就重复了：%s' % ids)
    boss = sorted(set(ids) & have)
    if boss:
        sys.exit('id 和已有课程撞了：%s' % boss)

    for l in LESSONS:
        for k in ('id', 'series', 'level', 'title', 'read', 'warn'):
            if not l.get(k) or not str(l[k]).strip():
                sys.exit('%s 缺 %s' % (l['id'], k))
        a = l['apply']
        if len(a['options']) != 4 or len(set(a['options'])) != 4:
            sys.exit('%s 的选项不对（要 4 个且不重复）' % l['id'])
        if not (0 <= a['answer'] <= 3):
            sys.exit('%s 的 answer 越界' % l['id'])
        if l['level'] not in ('A', 'B', 'C'):
            sys.exit('%s 的 level 不合法' % l['id'])
        for k, v in l.items():
            if k != 'apply' and '"' in v:
                sys.exit('%s.%s 里有 ASCII 双引号，换成 「」' % (l['id'], k))
        for v in a['options'] + [a['q'], a['why']]:
            if '"' in v:
                sys.exit('%s.apply 里有 ASCII 双引号，换成 「」' % l['id'])
        want = '选项 %d' % (a['answer'] + 1)
        if want not in a['why']:
            sys.exit('%s 的 why 里没有出现「%s」——编号和 answer 对不上' % (l['id'], want))
        if len(l['read']) < 400 or len(l['warn']) < 300:
            sys.exit('%s 写得太短了（read %d / warn %d）' % (l['id'], len(l['read']), len(l['warn'])))

    lessons.extend(LESSONS)
    # 注意：上面这两行必须是**原地修改**。第一版这里写的是
    #   `lessons = [l for l in lessons if l['id'] != DROP]`
    # ——那是**重新绑定**，data['lessons'] 还指着原来那个列表，于是文件里只有
    # version 被改了、内容一个字没动，而脚本照样打印「已摘掉 j04 / 39 课」。
    # 静默失败比报错危险得多，所以下面写完立刻回读校验。
    data['lessons'] = lessons
    data['version'] = data.get('version', 5) + 1
    with io.open(CUR, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write('\n')

    # 写完回读校验：不校验的话，上面那种静默失败能一路骗到构建完成
    back = json.load(io.open(CUR, encoding='utf-8'))['lessons']
    backIds = [l['id'] for l in back]
    if DROP in backIds:
        sys.exit('回读校验失败：%s 还在文件里' % DROP)
    for i in ids:
        if i not in backIds:
            sys.exit('回读校验失败：%s 没写进去' % i)
    if len(back) != len(lessons):
        sys.exit('回读校验失败：期望 %d 课，文件里 %d 课' % (len(lessons), len(back)))

    print('curriculum.json：%d 课（回读校验通过）' % len(back))
    print('系列：%s' % ' / '.join(sorted(set(x['series'] for x in back))))
    for l in LESSONS:
        print('  %s  %s  read %d 字  warn %d 字' % (l['id'], l['title'], len(l['read']), len(l['warn'])))


if __name__ == '__main__':
    main()
