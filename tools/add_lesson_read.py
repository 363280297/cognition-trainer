def main():
    with io.open(CUR, encoding='utf-8') as f:
        data = json.load(f)
    lessons = data['lessons']
    add = [l for l in LESSONS if not any(x['id'] == l['id'] for x in lessons)]
    if not add:
        print('已经加过了，跳过')
        return
    lessons.extend(add)
    with io.open(CUR, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('curriculum.json：%d 课（新增 %s）' % (len(lessons), ', '.join(l['id'] for l in add)))


if __name__ == '__main__':
    main()
