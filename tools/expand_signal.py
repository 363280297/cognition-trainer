def main() -> int:
    d = json.loads(P.read_text(encoding="utf-8"))
    have = {x["id"] for x in d["items"]}
    dup = [x["id"] for x in NEW if x["id"] in have]
    if dup:
        sys.exit(f"!! 这些 id 已经存在：{dup}")
    d["items"].extend(NEW)

    errs = []
    seen = set()
    for x in d["items"]:
        for f in ("id", "kind", "domain", "context", "cue", "why", "trap"):
            if not x.get(f) or not str(x[f]).strip():
                errs.append(f"{x.get('id')} 缺 {f}")
        if x["id"] in seen:
            errs.append(f"{x['id']} 重复")
        seen.add(x["id"])
        if x["kind"] not in ("signal", "base", "thin"):
            errs.append(f"{x['id']} kind 不认识：{x['kind']}")
        # 这一条最要紧：答案键错了，用户会在游戏里学到反的东西
        if (x["kind"] == "signal") != bool(x["exclusive"]):
            errs.append(f"{x['id']} kind={x['kind']} 与 exclusive={x['exclusive']} 矛盾")
        if len(x["why"]) < 30:
            errs.append(f"{x['id']} why 太短，等于没给判据")
        if len(x["trap"]) < 15:
            errs.append(f"{x['id']} trap 太短")
        if x["kind"] == "thin" and not x.get("settle"):
            errs.append(f"{x['id']} 信息不足却没写下一步看什么")
    if errs:
        print("!! 校验没过，未写回：")
        for e in errs:
            print("   " + e)
        return 1

    P.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")

    kinds = {}
    for x in d["items"]:
        kinds[x["kind"]] = kinds.get(x["kind"], 0) + 1
    n_yes = sum(1 for x in d["items"] if x["exclusive"])
    per = d.get("per_class_per_play", 10)
    print(f"信号场题库：{len(d['items'])} 条 {kinds}")
    print(f"  真信号 {n_yes} / 其余 {len(d['items']) - n_yes}，每局各抽 {per}")

    # 扩容的唯一目的是「别玩两局就把题看完」。所以要算的是**覆盖速度**：
    # 每局从某一类里随机抽 per 条，跨局相当于有放回，k 局之后见过的比例是
    # 1-(1-per/pool)^k。第一版我写的是 min(两类)/per，那算的是"抽完较小那一类
    # 需要几局"，和"会不会看到重复"是两回事，还把旧值硬编码成了 1.2 局。
    def plays_to_cover(pool, target=0.95):
        k = 0
        while k < 99:
            k += 1
            if 1 - (1 - per / pool) ** k >= target:
                return k
        return 99

    smaller = min(n_yes, len(d["items"]) - n_yes)
    now = plays_to_cover(smaller)
    before = plays_to_cover(12)          # 扩容前：真信号池 12 条
    print(f"  看完全部题所需局数：{before} → {now}（目标 95% 覆盖，取较小那一类算）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
