def main():
    with io.open(CUR, encoding='utf-8') as f:
        data = json.load(f)
    lessons = data['lessons']
    if any(l['id'] == LESSON['id'] for l in lessons):
        print('已经加过了，跳过')
        return
    lessons.append(LESSON)
    with io.open(CUR, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('curriculum.json：%d 课（新增 %s）' % (len(lessons), LESSON['id']))


if __name__ == '__main__':
    main()
