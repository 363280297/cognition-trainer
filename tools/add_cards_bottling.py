def main() -> None:
    data = json.loads(CARDS.read_text(encoding="utf-8"))
    cards = data["cards"]
    have = {c["id"] for c in cards}
    added = [c for c in NEW if c["id"] not in have]
    if not added:
        print("都已存在")
        return

    errs = []
    for c in added:
        for k in ("id", "type", "domain", "stage", "context", "quote",
                  "question", "options", "best", "explain", "principle", "action"):
            if not c.get(k):
                errs.append(f"{c['id']} 缺字段 {k}")
        ids = [o["id"] for o in c["options"]]
        if len(ids) != 4 or len(set(ids)) != 4:
            errs.append(f"{c['id']} 选项必须是 4 个且不重复")
        if c["best"] not in ids:
            errs.append(f"{c['id']} best 不在选项里")
    if errs:
        for e in errs:
            print("  " + e)
        sys.exit("校验失败，未写回")

    cards.extend(added)
    data["version"] = int(data.get("version", 1)) + 1
    data["note"] = (data.get("note", "") +
                    " 另有 8 张针对「憋需求 + 敏感 + 幽默」画像的卡（b01–b08）："
                    "透明度错觉（Gilovich 等 1998）、自我沉默（Jack & Dill）、"
                    "幽默的四风格（Martin；自贬型与满意度负相关）。").strip()
    CARDS.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    from collections import Counter
    print(f"已加入 {len(added)} 张，共 {len(cards)} 张（version {data['version']}）")
    print("domain:", dict(Counter(c["domain"] for c in cards)))
    print("新卡:", [c["id"] for c in added])
    print("\n下一步：py -3 tools/gen_diagnosis.py " + " ".join(c["id"] for c in added))


if __name__ == "__main__":
    main()
