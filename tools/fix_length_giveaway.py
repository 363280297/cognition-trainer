def main():
    with io.open(CARDS, encoding='utf-8') as f:
        data = json.load(f)
    cards = {c['id']: c for c in data['cards']}

    changed = 0
    for cid, opts in FIX.items():
        card = cards.get(cid)
        if not card:
            print('  找不到 %s' % cid)
            continue
        for oid, text in opts.items():
            o = next((x for x in card['options'] if x['id'] == oid), None)
            if o is None:
                print('  %s 里没有选项 %s' % (cid, oid))
                continue
            if o['err'] == '正解':
                print('  %s.%s 是正解，跳过（不能改正确答案）' % (cid, oid))
                continue
            o['text'] = text
            changed += 1

    with io.open(CARDS, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print('改写干扰项 %d 条，涉及 %d 张卡' % (changed, len(FIX)))

    # 复测
    worst = []
    over = 0
    for c in data['cards']:
        b = next(o for o in c['options'] if o['id'] == c['best'])
        others = [x for x in c['options'] if x['id'] != c['best']]
        m = max(len(x['text']) for x in others)
        r = len(b['text']) / m
        if r > 1.5:
            over += 1
            worst.append((round(r, 2), c['id']))
        if len(b['text']) > m:
            pass
    worst.sort(reverse=True)
    print('修完之后仍 >1.5 倍的卡: %d 张 %s' % (over, worst[:6]))


if __name__ == '__main__':
    main()
